# =====================================================================
# validation: shape, exit lane, safe entry lanes, and a reachability check
# =====================================================================
def _cell(rows, x, y):
    if x < 0 or x > 17:
        return '#'
    if y < 0:
        return '#'
    if y > 14:
        return '#'
    return rows[y][x]


def resolve(rows, hard=True):
    """Pick the hardest variant: helpers gone, optional spikes present."""
    out = []
    for r in rows:
        s = ''
        for ch in r:
            if ch == '1':
                ch = '.' if hard else '#'
            elif ch in '23':
                ch = '^' if hard else '.'
            s += ch
        out.append(s)
    return out


def standable(rows, x, y):
    """Player (1 column, 2 rows) can stand at column x with feet on row y+1."""
    below = _cell(rows, x, y + 1)
    if y + 1 == 15:
        below = '#'
    if not (below in SOLID or below in ONEWAY or below == 'F' or below == 'f'):
        return False
    for yy in (y, y - 1):
        if yy < 0:
            return False
        c = _cell(rows, x, yy)
        if c in SOLID or c in HAZARD:
            return False
    return True


def free(rows, x, y):
    c = _cell(rows, x, y)
    return c not in SOLID and c not in HAZARD


def reachable(rows, entry_cols):
    return search(rows, entry_cols)[0]


def search(rows, entry_cols):
    """Coarse grid search from the entry lane to the exit. Standing states are
    (column, body row) with the body occupying rows y-1..y."""
    wood_adjacent = set()
    for y in range(15):
        for x in range(18):
            if rows[y][x] == 'W':
                for dx in (-1, 1):
                    if 0 <= x + dx < 18 and free(rows, x + dx, y):
                        wood_adjacent.add((x + dx, y))
    start = [(x, 14) for x in entry_cols]
    seen = set(start)
    todo = list(start)
    goal = False
    ex0 = None
    for x in range(18):
        if rows[0][x] == '=':
            ex0 = x if ex0 is None else ex0
    while todo:
        x, y = todo.pop()
        # reached a ledge under the exit (feet within 3 rows of the ceiling)?
        if ex0 <= x <= ex0 + 3 and y <= 2:
            clear = all(free(rows, x, yy) for yy in range(1, y + 1))
            if clear:
                goal = True
                break
        spring = _cell(rows, x, y + 1) == 's'
        rise = 8 if spring else 3
        cand = []
        # walk / fall
        for dx in (-1, 1):
            nx = x + dx
            if 0 <= nx < 18 and free(rows, nx, y) and free(rows, nx, y - 1):
                if standable(rows, nx, y):
                    cand.append((nx, y))
                else:
                    ny = y
                    while ny < 14 and free(rows, nx, ny + 1) and not standable(rows, nx, ny):
                        ny += 1
                    if standable(rows, nx, ny):
                        cand.append((nx, ny))
                    for ddx in (-1, 1):
                        if 0 <= nx + ddx < 18 and standable(rows, nx + ddx, ny):
                            cand.append((nx + ddx, ny))
        # jumps
        for ty in range(max(1, y - rise), 15):
            dy = y - ty
            reach = 4 if dy <= 1 else 3 if dy <= 3 else 2
            if dy < 0:
                reach = 5
            for tx in range(x - reach, x + reach + 1):
                if not (0 <= tx < 18):
                    continue
                if not (standable(rows, tx, ty) or ((tx, ty + 1) in wood_adjacent and standable_air(rows, tx, ty))):
                    continue
                # head room: column x must be free up to the apex
                top = min(ty, y) - 1
                ok = all(free(rows, x, yy) for yy in range(max(0, ty - 1), y + 1)) if dy > 0 else True
                if dy > 0:
                    ok = ok and all(free(rows, tx, yy) for yy in range(max(0, ty - 1), ty + 1))
                if ok:
                    cand.append((tx, ty))
        for c in cand:
            if c not in seen:
                seen.add(c)
                todo.append(c)
    return goal, seen


def standable_air(rows, x, y):
    return free(rows, x, y) and free(rows, x, y - 1) and y >= 1


def entry_safe(rows, a, b):
    """No hazards or enemies right above the entry planks (the player arrives
    rising through them); solid blocks higher up only bump the player's head."""
    for y in range(10, 15):
        for x in range(a, b + 1):
            ch = rows[y][x]
            if ch in HAZARD or ch in 'EeBbGSZ-:C':
                return False
    return all(free(rows, x, y) for y in range(13, 15) for x in range(a, b + 1))


def validate(rooms):
    out = []
    order = sorted(range(len(rooms)), key=lambda i: (rooms[i]['special'] is None, i))
    for idx in order:
        r = rooms[idx]
        rows = r['rows']
        name = r['name']
        assert len(rows) == 15, (name, len(rows))
        for y, row in enumerate(rows):
            assert len(row) == 18, (name, y, row, len(row))
            for ch in row:
                assert ch == '.' or ch in NAMES, (name, ch)
        ceil = rows[0]
        assert set(ceil) <= set('#='), (name, ceil)
        exit_lane = None
        for k, (a, b) in LANES.items():
            if ceil[a:b + 1] == '====' and ceil.count('=') == 4:
                exit_lane = k
        assert exit_lane, (name, 'exit must be one 4-wide lane', ceil)
        hard = resolve(rows, True)
        mask = 0
        for k, (a, b) in LANES.items():
            safe = entry_safe(hard, a, b)
            if safe and reachable(hard, range(a, b + 1)):
                mask |= 1 << LANE_INDEX[k]
        assert mask, (name, 'no usable entry lane')
        if r['special']:
            need = 2 if r['special'] == 'ENTRANCE' else 7  # the run starts in the middle lane
            assert mask & need == need, (name, 'special room lanes', mask)
            SPECIAL[r['special']] = len(out)
        out.append(dict(name=name, tier=r['tier'], rows=rows, entry=mask, exit=LANE_INDEX[exit_lane], flags=r['flags']))
    # every exit lane must be enterable by some room of each tier band (mirroring maps L<->R)
    for tier in range(1, 6):
        pool = [o for o in out if o['tier'] <= tier and o['name'] not in ('entrance', 'rest')]
        for lane in range(3):
            mirrored = {0: 2, 1: 1, 2: 0}[lane]
            assert any(o['entry'] & (1 << lane) or o['entry'] & (1 << mirrored) for o in pool), (tier, lane)
    return out


if __name__ == '__main__':
    rs = validate(ROOMS)
    for r in rs:
        lanes = ''.join(k for k, i in LANE_INDEX.items() if r['entry'] & (1 << i))
        print(f"{r['name']:16} tier {r['tier']} entry {lanes:3} exit {'LMR'[r['exit']]}")
    print(len(rs), 'rooms')
