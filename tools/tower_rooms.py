"""Room templates for ARROW TOWER.

Each room is 18 columns (the tower walls on both sides are added by the game)
by 15 rows. Row 0 is the ceiling: stone with one 4-wide exit of planks ('=') in
lane L (cols 1-4), M (cols 7-10) or R (cols 13-16). The floor below row 14 is
the previous room's ceiling, so the player enters through whichever lane the
previous room exited from. The game mirrors rooms at random (L <-> R).

Movement budget (see tt_tower.c): a full jump rises 30 px (3.75 tiles), so
standing surfaces are at most 3 rows apart, and the ledge below the exit sits
on row 3. Horizontal reach is about 4 tiles while climbing 3 rows.

Legend
  .  empty            #  stone            W  wood (arrows stick)    =  plank (one-way)
  ^  spikes           v  ceiling spikes   %  crumbling block        s  spring
  o  coin             c  coin (50%)       g  gem                    h  heart (if hurt) or coin
  i  ice (Frost Vault), stone elsewhere   C  cannon (fires sideways into the room)
  I  icicle (falls in Frost Vault), ceiling spikes elsewhere
  1  helper block: only on easy floors    2  spikes from difficulty 2   3  spikes from difficulty 4
  E  slime            e  slime from difficulty 3
  B  bat              b  bat from difficulty 2                  G  ghost from difficulty 8
  S  saw on a horizontal track of '-'     Z  saw on a vertical track of ':'
  M  moving platform (left end) on a track of '~'
  F f  campfire (rest rooms)
"""

NAMES = {
    '#': 'STONE', 'W': 'WOOD', '=': 'PLANK', '^': 'SPIKE', 'v': 'SPIKE_D', '%': 'CRUMBLE', 's': 'SPRING',
    'o': 'COIN', 'c': 'COIN_MAYBE', 'g': 'GEM', 'h': 'HEART', 'i': 'ICE', 'C': 'CANNON', 'I': 'ICICLE',
    '1': 'HELPER', '2': 'SPIKE_D2', '3': 'SPIKE_D4', 'E': 'SLIME', 'e': 'SLIME_D3', 'B': 'BAT', 'b': 'BAT_D2',
    'G': 'GHOST', 'S': 'SAW_H', '-': 'TRACK_H', 'Z': 'SAW_V', ':': 'TRACK_V', 'M': 'PLATFORM', '~': 'TRACK_P',
    'F': 'FIRE', 'f': 'FIRE_R',
}
CODES = {ch: i + 1 for i, ch in enumerate(NAMES)}

LANES = {'L': (1, 4), 'M': (7, 10), 'R': (13, 16)}
LANE_INDEX = {'L': 0, 'M': 1, 'R': 2}

SOLID = set('#W%iC1')
ONEWAY = set('=sM~')
HAZARD = set('^v23I')
FLAG_WOOD = 1

ROOMS = []


def room(name, tier, text, flags=0, special=None):
    rows = [r.strip() for r in text.strip('\n').split('\n')]
    ROOMS.append(dict(name=name, tier=tier, rows=rows, flags=flags, special=special))


